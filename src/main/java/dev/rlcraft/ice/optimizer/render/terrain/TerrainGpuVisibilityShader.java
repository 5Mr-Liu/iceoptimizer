package dev.rlcraft.ice.optimizer.render.terrain;

/**
 * Current-frame inner-conservative coverage and ordered indirect commands.
 * Projection uses doubles once per face. Normalized float half-planes carry
 * an outward-rounded error bound for coefficient conversion and four float
 * operations over the entire viewport, so the cheaper cell tests only shrink
 * coverage. A full 8x8 tile is retained only when one real face proves every
 * point inside it; partial tiles still use individual full-cell proofs.
 */
final class TerrainGpuVisibilityShader {
    private TerrainGpuVisibilityShader() { }

    static String source() {
        return "#version 430 compatibility\n"
            + "layout(local_size_x=64) in;\n"
            + "layout(std430,binding=0) buffer Commands { uint commands[]; };\n"
            + "layout(std430,binding=1) readonly buffer Bounds { dvec4 bounds[]; };\n"
            + "layout(std430,binding=2) readonly buffer Faces { dvec4 faces[]; };\n"
            + "layout(std430,binding=3) coherent buffer Depth { uint cells[]; };\n"
            + "uniform dmat4 viewProjection;\n"
            + "uniform int stage, candidateCount, faceCount, commandCount, commandBase, commandStride;\n"
            + "const int W=160,H=90,TILES=14400,VIS=14640,WORK=18736;\n"
            + "const double EDGE=0.00001,BIAS=0.00002;\n"
            + "bool finiteValue(double v) { return !isnan(v)&&!isinf(v); }\n"
            + "dvec4 clipPoint(dvec3 p) { return viewProjection*dvec4(p,1.0); }\n"
            + "bool screen(dvec4 c,out dvec3 p) {\n"
            + " if (!(c.w>0.0000001 && c.z>-c.w+0.0000001 && c.z<c.w-0.0000001)) return false;\n"
            + " p=dvec3((c.xy/c.w*0.5+0.5)*dvec2(W,H),c.z/c.w*0.5+0.5);\n"
            + " return finiteValue(p.x)&&finiteValue(p.y)&&finiteValue(p.z); }\n"
            + "double edge(dvec2 a,dvec2 b,dvec2 p) { return (b.x-a.x)*(p.y-a.y)-(b.y-a.y)*(p.x-a.x); }\n"
            + "void prepareFace(uint face) {\n"
            + " dvec3 projected[4];vec4 planes[4];ivec4 rectangle;uint faceDepth=0u;\n"
            + " {\n"
            + "  rectangle=ivec4(0); bool valid=true; dvec2 lo=dvec2(1e300LF),hi=dvec2(-1e300LF); double far=0.0;\n"
            + "  for (int i=0;i<4;i++) { dvec3 p; if (!screen(clipPoint(faces[face*4u+uint(i)].xyz),p)) {valid=false;break;}\n"
            + "   projected[i]=p;lo=min(lo,p.xy);hi=max(hi,p.xy);far=max(far,p.z); }\n"
            + "  if (valid && edge(projected[0].xy,projected[1].xy,projected[2].xy)>EDGE && hi.x>0.0 && hi.y>0.0 && lo.x<double(W) && lo.y<double(H)) {\n"
            + "   rectangle=ivec4(ivec2(floor(clamp(lo,dvec2(0.0),dvec2(W,H)))),ivec2(ceil(clamp(hi,dvec2(0.0),dvec2(W,H)))));\n"
            + "   faceDepth=floatBitsToUint(float(min(1.0,far+BIAS)));\n"
            + "   for(int i=0;i<4;i++) { dvec2 a=projected[i].xy,delta=projected[(i+1)&3].xy-a;\n"
            + "    double length=abs(delta.x)+abs(delta.y); if(!(length>0.0)){rectangle=ivec4(0);break;}\n"
            + "    dvec2 normal=dvec2(-delta.y,delta.x)/length; double distance=dot(normal,a);\n"
            + "    vec3 rounded=vec3(normal,float(distance));\n"
            + "    double error=double(W)*abs(double(rounded.x)-normal.x)+double(H)*abs(double(rounded.y)-normal.y)+abs(double(rounded.z)-distance);\n"
            + "    error+=0.00000023841864LF*(double(W)+double(H)+abs(double(rounded.z)));\n"
            + "    error+=0.00000000000002LF*(1.0+abs(normal.x*a.x)+abs(normal.y*a.y));\n"
            + "    float inward=uintBitsToFloat(floatBitsToUint(float(EDGE*(1.0+length)/length+error))+1u);\n"
            + "    planes[i]=vec4(rounded,inward);\n"
            + "   } }\n"
            + " }\n"
            + " int at=WORK+int(face)*24;for(int i=0;i<4;i++)cells[at+16+i]=uint(rectangle[i]);cells[at+20]=faceDepth;\n"
            + " if(rectangle.x==rectangle.z||rectangle.y==rectangle.w)return;\n"
            + " for(int i=0;i<4;i++)for(int c=0;c<4;c++)cells[at+i*4+c]=floatBitsToUint(planes[i][c]);\n"
            + "}\n"
            + "void raster() {\n"
            + " uint invocation=gl_GlobalInvocationID.x,face=invocation/16u,lane=invocation&15u;if(face>=uint(faceCount))return;\n"
            + " int at=WORK+int(face)*24;ivec4 rectangle=ivec4(cells[at+16],cells[at+17],cells[at+18],cells[at+19]);\n"
            + " if(rectangle.x==rectangle.z||rectangle.y==rectangle.w)return;uint faceDepth=cells[at+20];vec4 planes[4];\n"
            + " for(int i=0;i<4;i++)for(int c=0;c<4;c++)planes[i][c]=uintBitsToFloat(cells[at+i*4+c]);\n"
            + " ivec2 tileStart=rectangle.xy/8,tileEnd=(rectangle.zw+7)/8;int tileWidth=tileEnd.x-tileStart.x;\n"
            + " int tileCount=tileWidth*(tileEnd.y-tileStart.y);\n"
            + " for(int ordinal=int(lane);ordinal<tileCount;ordinal+=16) {\n"
            + "  int tx=tileStart.x+ordinal%tileWidth,ty=tileStart.y+ordinal/tileWidth;\n"
            + "  int tile=TILES+ty*20+tx;if(faceDepth>=cells[tile])continue;\n"
            + "  ivec2 lo=ivec2(tx,ty)*8,hi=min(lo+8,ivec2(W,H));bool covered=true;\n"
            + "  for(int i=0;i<4;i++) {vec4 plane=planes[i];\n"
            + "   vec2 corner=vec2(plane.x<0.0?hi.x:lo.x,plane.y<0.0?hi.y:lo.y);\n"
            + "   if(!(dot(plane.xy,corner)-plane.z>plane.w)){covered=false;break;}}\n"
            + "  if(covered){atomicMin(cells[tile],faceDepth);continue;}\n"
            + "  lo=max(lo,rectangle.xy);hi=min(hi,rectangle.zw);\n"
            + "  for(int y=lo.y;y<hi.y;y++)for(int x=lo.x;x<hi.x;x++) {\n"
            + "   int cell=y*W+x;if(faceDepth>=cells[cell])continue;covered=true;\n"
            + "   for(int i=0;i<4;i++) {vec4 plane=planes[i];\n"
            + "    vec2 corner=vec2(x,y)+vec2(plane.x<0.0?1.0:0.0,plane.y<0.0?1.0:0.0);\n"
            + "    if(!(dot(plane.xy,corner)-plane.z>plane.w)){covered=false;break;}}\n"
            + "   if(covered)atomicMin(cells[cell],faceDepth);\n"
            + "  }\n"
            + " } }\n"
            + "void visibility(uint index) {\n"
            + " if(index>=uint(candidateCount))return; cells[VIS+int(index)]=1u;\n"
            + " dvec4 a=bounds[index*2u],b=bounds[index*2u+1u]; if(a.w==0.0)return;\n"
            + " dvec2 lo=dvec2(1e300LF),hi=dvec2(-1e300LF); double near=1.0;\n"
            + " for(int corner=0;corner<8;corner++) { dvec3 p= dvec3((corner&1)==0?a.x:b.x,(corner&2)==0?a.y:b.y,(corner&4)==0?a.z:b.z);\n"
            + "  dvec3 s;if(!screen(clipPoint(p),s))return;lo=min(lo,s.xy);hi=max(hi,s.xy);near=min(near,s.z); }\n"
            + " if(hi.x<0.0||hi.y<0.0||lo.x>double(W)||lo.y>double(H))return;\n"
            + " ivec2 first=ivec2(floor(clamp(lo-1.0,dvec2(0.0),dvec2(W,H))));\n"
            + " ivec2 end=ivec2(ceil(clamp(hi+1.0,dvec2(0.0),dvec2(W,H))));\n"
            + " if(any(lessThanEqual(end,first)))return;\n"
            + " double nearest=max(0.0,near-BIAS);\n"
            + " ivec2 tileEnd=(end+7)/8;\n"
            + " for(int ty=first.y/8;ty<tileEnd.y;ty++)for(int tx=first.x/8;tx<tileEnd.x;tx++) {\n"
            + "  uint tile=cells[TILES+ty*20+tx];if(nearest>double(uintBitsToFloat(tile))+BIAS)continue;\n"
            + "  ivec2 lo=max(first,ivec2(tx,ty)*8),hi=min(end,ivec2(tx+1,ty+1)*8);\n"
            + "  for(int y=lo.y;y<hi.y;y++)for(int x=lo.x;x<hi.x;x++)\n"
            + "   if(!(nearest>double(uintBitsToFloat(cells[y*W+x]))+BIAS))return; }\n"
            + " cells[VIS+int(index)]=0u; }\n"
            + "void main() { uint index=gl_GlobalInvocationID.x;\n"
            + " if(stage==0) { if(index<uint(VIS)) cells[index]=floatBitsToUint(1.0);if(index<uint(faceCount))prepareFace(index); }\n"
            + " else if(stage==1) raster();\n"
            + " else if(stage==3) visibility(index);\n"
            + " else if(stage==4 && index<uint(commandCount)) { int at=commandBase+int(index)*commandStride;\n"
            + "  uint candidate=commands[at+3]; if(candidate<uint(candidateCount))commands[at+1]*=cells[VIS+int(candidate)]; }\n"
            + "}\n";
    }
}
